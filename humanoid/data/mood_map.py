def get_mood_label(affection: float, libido: float, aggression: float) -> str:
    """按情绪三维数值取可读标签。"""
    table = AFFECTION_MAP.get(affection_rank(affection), {})
    return table.get((round_to_bucket(libido), round_to_bucket(aggression)), "普通")


def generate_mood_tag(affection: float, libido: float, aggression: float, energy: float) -> str:
    """生成「精力充沛，开心，亲切」这类可读心情标签。"""
    parts: list[str] = []

    if energy >= 70:
        parts.append("精力充沛")
    elif energy >= 40:
        parts.append("状态平稳")
    else:
        parts.append("有点疲惫")

    if affection >= 70:
        parts.append("开心")
    elif affection >= 40:
        parts.append("平静")
    else:
        parts.append("冷淡")

    if libido >= 30 and aggression < 20:
        parts.append("亲切")
    elif aggression >= 30 and libido < 20:
        parts.append("疏离")
    elif aggression >= 30 and libido >= 30:
        parts.append("矛盾")
    else:
        parts.append("自然")

    unique: list[str] = []
    for part in parts:
        if part not in unique:
            unique.append(part)
    return "，".join(unique)
