_LIBIDO_AGGRESSION_BUCKETS = (0.0, 12.5, 25.0, 37.5, 50.0)


def round_to_bucket(value: float) -> float:
    for bucket in _LIBIDO_AGGRESSION_BUCKETS:
        if value <= bucket:
            return bucket
    return 50.0


def affection_rank(affection: float) -> int:
    if affection < 12.5:
        return 0
    if affection < 37.5:
        return 25
    if affection < 62.5:
        return 50
    if affection < 87.5:
        return 75
    return 100


